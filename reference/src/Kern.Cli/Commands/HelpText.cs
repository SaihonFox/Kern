namespace Kern.Cli.Commands;

/// <summary>Тексты справки: общая (`kernc help`) и по каждой команде (`kernc help run`, `kernc run --help`).</summary>
internal static class HelpText
{
	public const string General = """
		kernc — компилятор и виртуальная машина языка Kern

		Использование:  kernc <команда> [путь] [параметры]

		Команды:
		  run     выполнить проект, файл .kern или .kbc
		  check   проверить код без запуска (только диагностики)
		  build   скомпилировать в байткод (.kbc) или собрать все цели build.kern
		  exe     автономное приложение: хост VM + program.kbc
		  test    выполнить функции с #[test]
		  dis     листинг байткода
		  dll     собрать библиотеку .kbc (без точки входа)
		  fmt     привести отступы и пробелы в .kern к единому виду
		  repl    интерактивная сессия
		  clean   удалить результаты сборки
		  tasks   список задач build.kern
		  do      выполнить задачи build.kern по именам
		  help    справка: kernc help [команда]
		  version версия

		Общие параметры:
		  -O0 | -O1 | -O2     уровень оптимизации (по умолчанию -O1)
		  --time              показать, сколько выполнялась команда (в stderr; для `run` — отдельно компиляция и выполнение)
		  -o <путь>           куда писать результат (build — файл, exe — папка)
		  --                  дальше идут аргументы запускаемой программы
		  -h, --help          справка по команде

		Путь — папка проекта (kern.toml), папка с build.kern, один файл .kern или .kbc.
		Без пути используется текущая папка. Подробнее: kernc help <команда>.
		""";

	private static readonly Dictionary<string, string> Commands = new()
	{
		["run"] = """
			kernc run [путь] [цель] [-O0..2] [--time] [-- аргументы]

			Компилирует и выполняет проект. Принимает папку, файл .kern или готовый .kbc.
			В папке с build.kern запускается цель с kind = "app": если она одна — ею, иначе укажите имя:
			  kernc run . app -- --port 8080
			С `--time` в конце печатается время: `[время] загрузка/компиляция: 120 мс, выполнение: 2.34 с`.
			Для автономного exe: переменная окружения KERN_TIME=1.
			""",
		["check"] = """
			kernc check [путь]

			Разбор и типизация без генерации кода: печатает ошибки и предупреждения с фрагментом строки.
			Код возврата 0 — ошибок нет.
			""",
		["build"] = """
			kernc build [путь] [задача...] [-O0..2] [-o файл.kbc]

			Папка без build.kern: компилирует проект в один .kbc (-o задаёт имя файла; по умолчанию `<проект>/out/<имя>.kbc`).
			Папка с build.kern: выполняет задачи (по умолчанию `build` — все цели). Результаты — в build/.
			Цель компилируется заново только при изменении исходников (хэш содержимого).
			""",
		["exe"] = """
			kernc exe [путь] [цель] [-o папка]

			Кладёт рядом хост VM (копия kernc) и program.kbc: папку можно переносить на машину без Kern
			(нужен .NET-рантайм, если приложение собрано framework-dependent).
			""",
		["test"] = """
			kernc test [путь]

			Выполняет все функции с атрибутом #[test] (в том числе async). Код возврата 1, если есть провалы.
			В папке с build.kern запускаются тесты всех целей.
			""",
		["dis"] = "kernc dis <путь>\n\nПечатает листинг байткода модуля (из исходников или .kbc).",
		["dll"] = """
			kernc dll [путь] [-O0..2] [-o файл.kbc]

			Компилирует проект как библиотеку: байткод без точки входа (`main`, если есть, отбрасывается).
			Запустить такой .kbc нельзя; он нужен как результат сборки библиотеки и для просмотра (kernc dis).
			В build.kern библиотеки — цели с kind = "lib"; зависимые цели подключают их через t.deps.
			""",
		["fmt"] = """
			kernc fmt [путь...] [--check] [--stdout]

			Нормализует отступы (4 пробела на уровень скобок) и пробелы: убирает хвостовые пробелы и табы в отступе,
			сжимает подряд идущие пустые строки, ставит один перевод строки в конце. Комментарии сохраняются.
			Файлы с синтаксическими ошибками не трогаются; перед записью проверяется, что токены не изменились.
			  --check    ничего не писать, код возврата 1, если нужно форматирование
			  --stdout   печатать результат вместо записи в файл
			Путь — файл или папка (рекурсивно, кроме bin/obj/build/dist).
			""",
		["repl"] = """
			kernc repl [-O0..2]

			Интерактивная сессия. Объявления (fun/type/unit/use) накапливаются; выражение вычисляется и печатается;
			объявления переменных и присваивания запоминаются и выполняются заново перед каждой следующей строкой.
			Команды: :help :decls :history :reset :quit.
			""",
		["clean"] = "kernc clean [путь]\n\nУдаляет каталог build/ рабочей области.",
		["tasks"] = "kernc tasks [путь]\n\nПечатает задачи, доступные в build.kern: встроенные (цель:compile, цель:run, цель:test, цель:exe, build, test, clean) и ваши.",
		["do"] = """
			kernc do <задача...> [путь] [-- аргументы]

			Выполняет задачи build.kern в указанном порядке вместе с их зависимостями (каждая — один раз).
			Задача цели: app:run, core:test. Свои задачи объявляются в build.kern:
			  w.task("hello") fun { println("привет") }
			""",
		["help"] = "kernc help [команда]\n\nСправка по kernc или по конкретной команде.",
		["version"] = "kernc version\n\nПечатает версию компилятора.",
	};

	public static bool TryGet(string command, out string text) => Commands.TryGetValue(command, out text!);
}
