namespace Kern.Cli.Commands;

/// <summary>Тексты справки: общая и по командам. Перечислены только реализованные команды.</summary>
internal static class HelpText
{
	public const string General = """
		kernc — компилятор и виртуальная машина языка Kern

		Использование: kernc <команда> [аргументы]

		Команды:
		  run <файл.kern> [аргумент ...]     скомпилировать и выполнить fun main
		  run <папка> [аргумент ...]         проект: src/**/*.kern или *.kern
		  check <файл.kern|папка>            только проверить, без записи файлов
		  build <файл.kern> [-o <файл.kbc>]  скомпилировать и записать байткод
		  build <папка> [-o <файл.kbc>]      проект → <папка>/out/<имя>.kbc
		  clean <папка>                      удалить out/ и dist/
		  dis <файл.kbc>                     текстовый листинг байткода
		  help [команда]                     справка
		  version                            версия

		Справка по команде: kernc help run
		""";

	private static readonly Dictionary<string, string> Commands = new(StringComparer.Ordinal)
	{
		["run"] = """
			kernc run <файл.kern> [аргумент ...]
			kernc run <папка> [аргумент ...]

			Компилирует один файл или проект по соглашению и выполняет его top-level fun main.
			Проект: источники <папка>/src/**/*.kern, а если src/ нет — <папка>/*.kern; имя
			проекта — имя папки. Всё после исходника — аргументы программы:
			main(list<str> args) получает их списком, main без параметров их игнорирует.
			Программа печатает в стандартный вывод (print/println); возвращаемое значение main
			игнорируется. Диагностики компиляции и ошибки выполнения печатаются в стандартный
			поток ошибок. Запуск папки требует main во всём проекте.
			Коды возврата: 0 — успех, 1 — ошибка компиляции или выполнения, 2 — неверные аргументы.
			""",
		["check"] = """
			kernc check <файл.kern|папка>

			Компилирует файл или проект по соглашению и печатает все диагностики
			(путь:строка:колонка, путь для проекта относителен его папке). Ничего не
			записывает: ни out/, ни .kbc.
			Коды возврата: 0 — ошибок нет, 1 — ошибка компиляции или чтения, 2 — неверные аргументы.
			""",
		["build"] = """
			kernc build <файл.kern> [-o <файл.kbc>]
			kernc build <папка> [-o <файл.kbc>]

			Компилирует файл или проект по соглашению и записывает байткод .kbc. Для файла
			без -o путь тот же, что у исходника, с расширением .kbc; для папки —
			<папка>/out/<имя>.kbc (каталог out/ создаётся). Модуль без fun main — обычная
			библиотека. Написанный путь печатается в стандартный вывод.
			Коды возврата: 0 — успех, 1 — ошибка компиляции или записи, 2 — неверные аргументы.
			""",
		["clean"] = """
			kernc clean <папка>

			Рекурсивно удаляет результаты сборки проекта: <папка>/out и <папка>/dist.
			Отсутствие этих каталогов — не ошибка; печатается, что удалено.
			Коды возврата: 0 — успех, 1 — не удалось удалить, 2 — неверные аргументы
			(аргумент не папка).
			""",
		["dis"] = """
			kernc dis <файл.kbc>

			Читает модуль .kbc и печатает листинг: пулы строк, констант, сигнатур типов,
			типы, поля, свойства, функции с инструкциями и таблицу строк.
			Коды возврата: 0 — успех, 1 — файл повреждён, 2 — неверные аргументы.
			""",
		["help"] = "kernc help [команда] — общая справка или справка по команде.",
		["version"] = "kernc version — версия kernc.",
	};

	public static bool TryGet(string command, out string? text) => Commands.TryGetValue(command, out text);
}
