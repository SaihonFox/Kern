namespace Kern.Cli.Commands;

/// <summary>Тексты справки: общая и по командам. Перечислены только реализованные команды.</summary>
internal static class HelpText
{
	public const string General = """
		kernc — компилятор и виртуальная машина языка Kern

		Использование: kernc <команда> [аргументы]

		Команды:
		  run <файл.kern> [аргумент ...]     скомпилировать и выполнить fun main
		  run <папка> [аргумент ...]         проект: src/**/*.kern или *.kern
		  check <файл.kern|папка>            только проверить, без записи файлов
		  test <файл.kern|папка>             запустить функции #[test]
		  build <файл.kern> [-o <файл.kbc>]  скомпилировать и записать байткод
		  build <папка> [-o <файл.kbc>]      проект → out/<имя>.kbc; с build.kern — по целям
		  dll <папка> [-o <файл.kbc>]        библиотека .kbc с интерфейсными исходниками
		  exe <папка>                        dist/<имя>[.exe] = хост + program.kbc
		  tasks [папка]                      цели, задачи и их зависимости
		  do <задача> [папка]                выполнить задачу build.kern
		  clean <папка>                      удалить out/ и dist/
		  fmt [путь…] [--check] [--stdout]   табы и CRLF, без хвостовых пробелов
		  repl                              интерактивные объявления и выражения
		  dis <файл.kbc>                     текстовый листинг байткода
		  help [команда]                     справка
		  version                            версия

		Справка по команде: kernc help run
		""";

	private static readonly Dictionary<string, string> Commands = new(StringComparer.Ordinal)
	{
		["run"] = """
			kernc run <файл.kern> [аргумент ...]
			kernc run <папка> [аргумент ...]

			Компилирует один файл или проект по соглашению и выполняет его top-level fun main.
			Проект: источники <папка>/src/**/*.kern, а если src/ нет — <папка>/*.kern; имя
			проекта — имя папки. Всё после исходника — аргументы программы:
			main(list<str> args) получает их списком, main без параметров их игнорирует.
			Программа печатает в стандартный вывод (print/println); возвращаемое значение main
			игнорируется. Диагностики компиляции и ошибки выполнения печатаются в стандартный
			поток ошибок. Запуск папки требует main во всём проекте.
			Коды возврата: 0 — успех, 1 — ошибка компиляции или выполнения, 2 — неверные аргументы.
			""",
		["check"] = """
			kernc check <файл.kern|папка>

			Компилирует файл или проект по соглашению и печатает все диагностики
			(путь:строка:колонка, путь для проекта относителен его папке). Ничего не
			записывает: ни out/, ни .kbc.
			Коды возврата: 0 — ошибок нет, 1 — ошибка компиляции или чтения, 2 — неверные аргументы.
			""",
		["test"] = """
			kernc test <файл.kern|папка>

			Компилирует файл, проект по соглашению или проект с build.kern и вызывает
			каждую функцию с атрибутом #[test] без аргументов. Для build.kern тесты
			запускаются для всех целей; для папки по соглашению — для её единственной
			цели. Паника в тесте (assert*/fail) считается ошибкой теста, остальные тесты
			продолжают выполняться. Диагностики компиляции и ошибки печатаются в stdout/stderr.
			Коды возврата: 0 — тестов нет или все прошли, 1 — ошибка компиляции или теста,
			2 — неверные аргументы.
			""",
		["build"] = """
			kernc build <файл.kern> [-o <файл.kbc>]
			kernc build <папка> [-o <файл.kbc>]

			Компилирует файл, проект по соглашению или проект с build.kern и записывает
			байткод .kbc. Папка с build.kern собирается по целям сценария: исходники цели
			и её deps компилируются одним модулем с именем цели, app-цель пишется в
			<папка>/out/<цель>.kbc, lib-цель проверяется как зависимость. Без build.kern
			источники — <папка>/src/**/*.kern (иначе <папка>/*.kern), результат —
			<папка>/out/<имя>.kbc. Для файла без -o путь тот же с расширением .kbc.
			build.kern — обычный код Kern: он выполняется виртуальной машиной при каждой
			сборке (и может делать что угодно) и читает переменные окружения через w.env.
			-o применим только к файлу, проекту по соглашению или проекту с одной app-целью.
			Написанные пути печатаются в стандартный вывод.
			Коды возврата: 0 — успех, 1 — ошибка компиляции, сценария или записи,
			2 — неверные аргументы.
			""",
		["tasks"] = """
			kernc tasks [папка]

			Печатает проект, цели с их видом и зависимостями (deps), затем задачи
			w.task/t.task; для задачи с after перечислены предварительные задачи.
			Подпроекты w.include(path) печатаются отдельными строками.
			Папка по умолчанию — текущая. Без build.kern показывается одна цель
			по соглашению. Список встроенных задач печатается последней строкой:
			<цель>:compile|run|exe|dll|check|dis|test, :compile, :clean.
			Коды возврата: 0 — успех, 1 — ошибка сценария сборки, 2 — неверные аргументы.
			""",
		["do"] = """
			kernc do <задача> [папка] [-p <профиль>]

			Выполняет задачу build.kern: имя из w.task, target:имя из t.task или
			встроенную задачу :compile (все цели), :clean, <цель>:compile|run|exe|dll|
			check|dis|test. Сначала в топологическом порядке выполняются задачи из after,
			каждая ровно один раз; цикл в after — ошибка. Перед выполнением печатается
			«задача <id>», для :compile — также записанные .kbc.
			Папка по умолчанию — текущая.
			Коды возврата: 0 — успех, 1 — ошибка задачи или сборки, 2 — неверные аргументы.
			""",
		["dll"] = """
			kernc dll <папка> [-o <файл.kbc>] [-O0..-O2] [-p <профиль>]

			Собирает библиотеку: .kbc с настоящим кодом и встроенными интерфейсными
			исходниками (атрибут kern.stub), чтобы потребитель мог писать
			use mathx.vec[…]. По умолчанию цель — единственная lib-цель build.kern или
			проект по соглашению без main; результат — <папка>/out/<имя>.kbc.
			Потребитель подключает файл через t.kbc("../mathx/out/mathx.kbc").
			Коды возврата: 0 — успех, 1 — ошибка сборки, 2 — неверные аргументы.
			""",
		["exe"] = """
			kernc exe <папка> [-O0..-O2] [-p <профиль>]

			Собирает app-цель и кладёт в <папка>/dist/<имя>[.exe] хост kernc вместе
			с program.kbc; запуск файла выполняет программу (аргументы передаются в main).
			Коды возврата: 0 — успех, 1 — ошибка сборки, 2 — неверные аргументы.
			""",
		["clean"] = """
			kernc clean <папка>

			Рекурсивно удаляет результаты сборки проекта: <папка>/out и <папка>/dist.
			Отсутствие этих каталогов — не ошибка; печатается, что удалено.
			Коды возврата: 0 — успех, 1 — не удалось удалить, 2 — неверные аргументы
			(аргумент не папка).
			""",
		["fmt"] = """
			kernc fmt [путь…] [--check] [--stdout]

			Приводит .kern файлы к табам и CRLF, убирает хвостовые пробелы и лишние пустые
			строки. Без путей форматирует текущую папку. --check только проверяет (код 1, если
			есть что менять), --stdout печатает результат одного файла. Токены до и после
			сверяются: при расхождении файл не трогается.
			""",
		["repl"] = """
			kernc repl

			Построчный ввод: объявления и присваивания запоминаются и повторяются перед каждой
			строкой, выражения печатаются. :quit — выход, :help — справка.
			""",
		["dis"] = """
			kernc dis <файл.kbc>

			Читает модуль .kbc и печатает листинг: пулы строк, констант, сигнатур типов,
			типы, поля, свойства, функции с инструкциями и таблицу строк.
			Коды возврата: 0 — успех, 1 — файл повреждён, 2 — неверные аргументы.
			""",
		["help"] = "kernc help [команда] — общая справка или справка по команде.",
		["version"] = "kernc version — версия kernc.",
	};

	public static bool TryGet(string command, out string? text) => Commands.TryGetValue(command, out text);
}
